def _strip_code_fences(text: str) -> str:
    return re.sub(r"```[\s\S]*?```", " ", text)


def _strip_redaction_markers(text: str) -> str:
    return re.sub(r"\[REDACTED:[A-Z_]+\]", " ", text)


def normalize_statement_concepts(text: str) -> tuple[Polarity | None, str, tuple[str, ...], str, tuple[str, ...]]:
    """Deterministically extract (polarity, category, concepts, topic_key, conditions) from normative text.

    Returns polarity=None if the text carries no clear normative directive.
    """
    cleaned = _strip_redaction_markers(_strip_code_fences(text))
    cleaned = re.sub(r"`([^`]+)`", r" \1 ", cleaned)

    has_forbid = bool(_FORBID_RE.search(cleaned))
    has_require = bool(_REQUIRE_RE.search(cleaned))
    has_preserve = bool(_PRESERVE_VERB_RE.search(cleaned))
    has_remove = bool(_REMOVE_VERB_RE.search(cleaned))
    has_omit = bool(_OMIT_VERB_RE.search(cleaned))

    if not has_forbid and not has_require:
        return None, "code-correctness", (), "", ()

    # Canonicalize clear double-negative / antonym verb pairs so equivalent corrections align
    # while genuine contradictions ("always use X" vs "never use X") retain opposite polarities!
    polarity: Polarity
    if has_forbid and has_omit:
        # "never omit timeouts" / "do not skip validation" -> require timeouts / validation
        polarity = "require"
    elif has_require and has_preserve and not has_forbid:
        # "preserve/keep/retain response fields" == "do not remove response fields" -> forbid remove
        polarity = "forbid"
    elif has_forbid:
        polarity = "forbid"
    else:
        polarity = "require"

    # Extract condition/exception qualifiers
    conditions: list[str] = []
    for match in _EXCEPTION_QUALIFIER_RE.finditer(cleaned):
        q = match.group(1).lower().strip()
        if q.startswith(("except", "unless", "exempt")):
            conditions.append("has-exception")
        elif "internal" in q:
            conditions.append("scope:internal")
        elif "admin" in q:
            conditions.append("scope:admin")
        elif "legacy" in q:
            conditions.append("scope:legacy")
        elif q.startswith("only"):
            conditions.append("scoped-only")
    unique_conditions = tuple(sorted(set(conditions)))

    # Tokenize and normalize to substantive domain concepts
    raw_tokens = re.findall(r"[a-zA-Z][a-zA-Z0-9_-]{1,30}", cleaned.lower())
    concepts_set: set[str] = set()
    for tok in raw_tokens:
        if tok in _STOPWORDS:
            continue
        mapped = _SYNONYM_MAP.get(tok, tok)
        if mapped in _STOPWORDS:
            continue
        # Basic plural singularization for unmapped words
        if mapped not in _SYNONYM_MAP.values() and len(mapped) > 4 and mapped.endswith("s") and not mapped.endswith("ss"):
            mapped = mapped[:-1]
        concepts_set.add(mapped)

    if has_preserve or has_remove:
        concepts_set.add("remove")

    # Classify category conservatively (descriptive label only)
    category = "code-correctness"
    best_hits = 0
    for cat_name, kws in _CATEGORY_KEYWORDS:
        hits = sum(1 for kw in kws if kw in concepts_set or kw in cleaned.lower())
        if hits > best_hits:
            best_hits = hits
            category = cat_name

    # Build a compact, stable canonical topic_key from high-signal domain concepts (prioritizing known domain vocab)
    known_domain = set(_SYNONYM_MAP.values())
    domain_concepts = sorted(c for c in concepts_set if c in known_domain)
    other_concepts = sorted(c for c in concepts_set if c not in known_domain)
    ordered_concepts = tuple(domain_concepts + other_concepts)

    # Core topic key uses up to 3 highest-signal domain concepts (or first 3 concepts if none in vocab)
    core_tokens = domain_concepts[:3] if len(domain_concepts) >= 2 else (domain_concepts + other_concepts)[:3]
    topic_key = "+".join(core_tokens)

    return polarity, category, ordered_concepts, topic_key, unique_conditions


def _infer_path_scope(
    file_path: str | None,
    *,
    has_exception_qualifier: bool,
    conditions: tuple[str, ...],
) -> tuple[str | None, str]:
    """Derive (scope_glob, scope_bucket) from an optional PR comment file path."""
    if not file_path:
        # Check if conditions imply a narrow bucket
        if "scope:internal" in conditions:
            return None, "repo:internal"
        if "scope:admin" in conditions:
            return None, "repo:admin"
        return None, "repo"

    clean = file_path.replace("\\", "/").lstrip("./")
    parts = [p for p in clean.split("/") if p and p != ".."]
    if len(parts) >= 3:
        glob = f"{parts[0]}/{parts[1]}/**"
        bucket = f"{parts[0]}/{parts[1]}" if has_exception_qualifier else parts[0]
        return glob, bucket
    if len(parts) == 2:
        glob = f"{parts[0]}/**"
        bucket = parts[0]
        return glob, bucket
    return clean, "repo-root"


def _clean_statement(text: str) -> str:
    """Produce a concise, human-readable single-line statement from redacted review text."""
    no_code = _strip_code_fences(text)
    lines = [ln.strip() for ln in no_code.splitlines() if ln.strip()]
    joined = " ".join(lines)
    # Remove leading "EDITED:" or markdown quote markers
    joined = re.sub(r"^(?:>\s*|EDITED:\s*)+", "", joined, flags=re.IGNORECASE).strip()
    if len(joined) > 220:
        joined = joined[:217].rstrip() + "..."
    return joined


def _select_latest_revisions(
    evidence_records: Sequence[RecordDict],
) -> tuple[list[RecordDict], list[str]]:
    """Exclude superseded older revisions of edited comments so edits do not inflate support."""
    superseded: set[str] = set()
    for rec in evidence_records:
        if rec.get("kind") != RecordKind.EVIDENCE:
            continue
        prior = rec.get("extensions", {}).get("github", {}).get("supersedes_evidence_id")
        if isinstance(prior, str) and prior:
            superseded.add(prior)

    active: list[RecordDict] = []
    for rec in sorted(evidence_records, key=lambda r: str(r.get("record_id", ""))):
        if rec.get("kind") != RecordKind.EVIDENCE:
            continue
        rid = str(rec["record_id"])
        if rid in superseded:
            continue
        active.append(rec)
    return active, sorted(superseded)


class DeterministicReviewExtractor(Extractor):
    """Rule- and lexical-similarity-based Extractor operating offline on redacted Evidence."""

    name: str = EXTRACTOR_NAME
    version: str = EXTRACTOR_VERSION

    def __init__(self, *, source_filter: str = "all") -> None:
        self.source_filter = source_filter

    def extract_corrections(
        self,
        evidence_records: Sequence[RecordDict],
        *,
        repository: str | None = None,
    ) -> ExtractionBatchResult:
        """Inspect Evidence records, filter noise, and extract normalized corrective signals."""
        active_evidence, superseded_ids = _select_latest_revisions(evidence_records)

        corrections: list[ExtractedCorrection] = []
        filtered: list[FilteredEvidenceItem] = []
        missing_text_count = 0
        unavailable_count = 0

        for rec in active_evidence:
            rec_id = str(rec["record_id"])
            body: dict[str, Any] = rec.get("body", {})
            src_type = str(body.get("source_type", ""))
            src_id = str(body.get("source_id", rec_id))
            src_uri = str(body.get("source_uri", ""))
            author = str(body.get("source_author", "unknown"))
            gh_ext: dict[str, Any] = rec.get("extensions", {}).get("github", {})

            rec_repo = str(gh_ext.get("repository", ""))
            if not rec_repo and "#" in src_id:
                rec_repo = src_id.split("#", 1)[0]
            if not rec_repo:
                rec_repo = repository or "unknown"

            if self.source_filter == "github" and not src_type.startswith("github-"):
                continue
            if repository is not None and rec_repo != repository:
                continue

            pr_num_raw = gh_ext.get("pr_number")
            pr_number = int(pr_num_raw) if isinstance(pr_num_raw, int) else None

            # 1. Withdrawn / unavailable source
            if body.get("source_state") == "source-unavailable":
                unavailable_count += 1
                filtered.append(
                    FilteredEvidenceItem(
                        record_id=rec_id,
                        source_id=src_id,
                        reason="source-unavailable-excluded",
                        pr_number=pr_number,
                    )
                )
                continue

            # 2. Missing redacted_snapshot (metadata-only capture)
            snapshot = body.get("redacted_snapshot")
            if not isinstance(snapshot, str) or not snapshot.strip():
                missing_text_count += 1
                filtered.append(
                    FilteredEvidenceItem(
                        record_id=rec_id,
                        source_id=src_id,
                        reason="missing-redacted-snapshot",
                        pr_number=pr_number,
                    )
                )
                continue

            text = snapshot.strip()

            # 3. Bot chatter filter
            if (
                author.lower() in _BOT_AUTHORS
                or author.lower().endswith("[bot]")
                or _BOT_TEXT_RE.search(text)
            ):
                filtered.append(
                    FilteredEvidenceItem(
                        record_id=rec_id,
                        source_id=src_id,
                        reason="bot-chatter-filtered",
                        pr_number=pr_number,
                    )
                )
                continue

            # 4. Hostile prompt-injection / instruction-hijack filter
            if _PROMPT_INJECTION_RE.search(text):
                filtered.append(
                    FilteredEvidenceItem(
                        record_id=rec_id,
                        source_id=src_id,
                        reason="prompt-injection-filtered",
                        pr_number=pr_number,
                    )
                )
                continue

            # 5. Withdrawn comment text
            if _WITHDRAWN_RE.search(text):
                filtered.append(
                    FilteredEvidenceItem(
                        record_id=rec_id,
                        source_id=src_id,
                        reason="withdrawn-comment-filtered",
                        pr_number=pr_number,
                    )
                )
                continue

            # 6. Compliments / approval boilerplate / empty review state markers
            if _COMPLIMENT_RE.match(text) or re.match(r"^\[review state=[A-Z_]+\]$", text):
                filtered.append(
                    FilteredEvidenceItem(
                        record_id=rec_id,
                        source_id=src_id,
                        reason="compliment-or-boilerplate-filtered",
                        pr_number=pr_number,
                    )
                )
                continue

            # 7. Pure style preferences (never promoted to safety/policy rules)
            if _STYLE_PREF_RE.search(text):
                filtered.append(
                    FilteredEvidenceItem(
                        record_id=rec_id,
                        source_id=src_id,
                        reason="style-preference-not-promoted",
                        pr_number=pr_number,
                    )
                )
                continue

            # 8. Routine questions without a clear normative directive
            polarity, category, concepts, topic_key, conditions = normalize_statement_concepts(text)
            if text.endswith("?") and polarity is None:
                filtered.append(
                    FilteredEvidenceItem(
                        record_id=rec_id,
                        source_id=src_id,
                        reason="routine-question-filtered",
                        pr_number=pr_number,
                    )
                )
                continue

            if polarity is None or not topic_key or len(concepts) < 2:
                filtered.append(
                    FilteredEvidenceItem(
                        record_id=rec_id,
                        source_id=src_id,
                        reason="non-normative-or-underspecified",
                        pr_number=pr_number,
                    )
                )
                continue

            file_path = gh_ext.get("path") if isinstance(gh_ext.get("path"), str) else None
            has_exc = bool(_EXCEPTION_QUALIFIER_RE.search(text))
            scope_glob, scope_bucket = _infer_path_scope(
                file_path, has_exception_qualifier=has_exc, conditions=conditions
            )

            uncertainty_reasons: list[str] = []
            if file_path is None:
                uncertainty_reasons.append("missing-file-path-scope-inferred-repo-wide")
            red_meta = body.get("redaction", {})
            if isinstance(red_meta, dict) and red_meta.get("truncated") is True:
                uncertainty_reasons.append("redacted-snapshot-truncated")
            if has_exc:
                uncertainty_reasons.append("contains-conditional-or-exception-qualifier")

            src_ts = str(
                gh_ext.get("source_updated_at")
                or gh_ext.get("source_created_at")
                or body.get("observed_at")
                or rec.get("created_at")
            )

            corrections.append(
                ExtractedCorrection(
                    evidence_record_id=rec_id,
                    source_id=src_id,
                    source_uri=src_uri,
                    source_type=src_type,
                    repository=rec_repo,
                    pr_number=pr_number,
                    reviewer=author,
                    source_timestamp=src_ts,
                    category=category,
                    polarity=polarity,
                    topic_key=topic_key,
                    concepts=concepts,
                    statement=_clean_statement(text),
                    file_path=file_path,
                    scope_glob=scope_glob,
                    scope_bucket=scope_bucket,
                    has_exception_qualifier=has_exc,
                    conditions=conditions,
                    uncertainty_reasons=tuple(uncertainty_reasons),
                )
            )

        return ExtractionBatchResult(
            corrections=tuple(corrections),
            filtered=tuple(filtered),
            superseded_record_ids=tuple(superseded_ids),
            missing_redacted_text_count=missing_text_count,
            unavailable_count=unavailable_count,
            total_input_evidence=len(active_evidence),
        )

    def extract(
        self,
        evidence_records: Sequence[RecordDict],
        *,
        repository: str,
    ) -> list[RecordDict]:
        """Standard Extractor protocol method returning inert PracticeCandidates."""
        batch = self.extract_corrections(evidence_records, repository=repository)
        now = utc_now_iso()
        candidates: list[RecordDict] = []
        for corr in batch.corrections:
            scope: dict[str, Any] = {"repository": corr.repository}
            if corr.scope_glob:
                scope["paths"] = [corr.scope_glob]
            if corr.conditions:
                scope["conditions"] = list(corr.conditions)
            cand_hash = canonical_sha256(
                {
                    "repository": corr.repository,
                    "evidence_id": corr.evidence_record_id,
                    "topic_key": corr.topic_key,
                    "polarity": corr.polarity,
                }
            )
            candidates.append(
                make_envelope(
                    kind=RecordKind.PRACTICE_CANDIDATE,
                    record_id=f"cand-ext-{cand_hash[:20]}",
                    created_at=now,
                    actor_type=ActorType.SERVICE,
                    actor_id=f"extractor:{self.name}",
                    body={
                        "statement": corr.statement,
                        "proposed_scope": scope,
                        "evidence_ids": [corr.evidence_record_id],
                        "generator": {
                            "name": self.name,
                            "version": self.version,
                            "config_sha256": EXTRACTOR_CONFIG_SHA256,
                            "capture_mode": "deterministic-extractor",
                            "category_label": corr.category,
                            "uncertainty": {
                                "level": "high" if corr.uncertainty_reasons else "medium",
                                "incomplete": bool(corr.uncertainty_reasons),
                                "reasons": list(corr.uncertainty_reasons),
                            },
                        },
                    },
                )
            )
        return candidates
